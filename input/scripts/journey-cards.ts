#!/usr/bin/env bun
/**
 * The home page's journey cards, one per moment of the pilgrim's journey,
 * generated from the user scenarios so nothing is typed twice.
 *
 * As smart-trust-demo lays out its "Four moments that matter": each card has
 * the moment's illustration (input/images/pilgrim/pN.webp), its title, when
 * and where, its headline (the scenario's first step), and links to walk
 * through it in the journeys viewer, to read it in the pilgrim's journey, and
 * to its ArchiMate view (archimate/build.py gives each moment's view the
 * moment's id as its slug).
 *
 * Usage:
 *   bun input/scripts/journey-cards.ts           # write input/includes/journey-cards.html
 *   bun input/scripts/journey-cards.ts --check   # fail when the committed file is stale
 */
import { existsSync, readFileSync, readdirSync, writeFileSync, mkdirSync } from "node:fs";
import { join, resolve } from "node:path";

const ROOT = resolve(import.meta.dir, "..", "..");
const OUT = join(ROOT, "input/includes/journey-cards.html");
const VIEWER = "en/smart-ips-pilgrimage/journeys/smart-ips-pilgrimage";
const VERSION = /^version:\s*(\S+)/m.exec(readFileSync(join(ROOT, "sushi-config.yaml"), "utf8"))![1];
const VIEWS = `en/smart-ips-pilgrimage/archimate/${VERSION}/views`;

interface Step { headline?: string; narrative?: string }
interface Scenario { id: string; title: string; when?: string; where?: string; partOf?: string; steps?: Step[] }

const esc = (s: string) => s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");

export function cards(): string {
  const dir = join(ROOT, "user-scenarios");
  const all = readdirSync(dir).filter((f) => f.endsWith(".json")).sort()
    .map((f) => JSON.parse(readFileSync(join(dir, f), "utf8")) as Scenario);
  const moments = all.filter((s) => s.partOf);
  const out = [
    "<!-- Generated by input/scripts/journey-cards.ts from user-scenarios/. Do not edit; edit the scenarios and rerun. -->",
    '<div style="display:grid;grid-template-columns:repeat(auto-fit,minmax(230px,1fr));gap:14px;margin:12px 0 24px">',
  ];
  for (const m of moments) {
    const code = m.id.split("-")[0];
    const walk = `${VIEWER}/${m.id}/`;
    const [label, ...rest] = m.title.split(" · ");
    const text = m.steps?.[0]?.headline ?? m.steps?.[0]?.narrative ?? "";
    out.push(
      '<div style="border:1px solid #e2e8f0;border-radius:14px;padding:14px;background:#fff;color:#1e293b">',
      `<a href="${walk}" title="Walk through this moment"><img src="pilgrim/${code}.webp" alt="${esc(m.title)}" style="width:100%;border-radius:10px"/></a>`,
      `<div style="font-weight:700;font-size:1.1em;margin-top:8px">${esc(rest.join(" · ") || m.title)}</div>`,
      `<div style="font-size:.8em;color:#64748b">${esc([m.when, m.where, label].filter(Boolean).join(" · "))}</div>`,
      `<p style="font-size:.9em;margin:6px 0">${esc(text)}</p>`,
      `<div style="font-size:.85em"><a href="${walk}"><b>Walk through it</b></a> · <a href="pilgrim-journey.html">Story</a> · <a href="${VIEWS}/${m.id}/">ArchiMate view</a></div>`,
      "</div>",
    );
  }
  out.push("</div>", "");
  return out.join("\n");
}

if (import.meta.main) {
  const want = cards();
  if (process.argv.includes("--check")) {
    const have = existsSync(OUT) ? readFileSync(OUT, "utf8") : "";
    if (have !== want) {
      console.error("input/includes/journey-cards.html: stale; run bun input/scripts/journey-cards.ts");
      process.exit(1);
    }
    console.log("input/includes/journey-cards.html: current");
  } else {
    mkdirSync(join(ROOT, "input/includes"), { recursive: true });
    writeFileSync(OUT, want);
    console.log("input/includes/journey-cards.html: written");
  }
}
