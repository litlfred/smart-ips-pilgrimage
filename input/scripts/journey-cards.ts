#!/usr/bin/env bun
/**
 * The home page's journey cards, one per moment of the pilgrim's journey,
 * generated from the user scenarios so nothing is typed twice.
 *
 * As smart-trust-demo lays out its "Four moments that matter": each card has
 * the moment's illustration (input/images/pilgrim/pN.webp), its title, when
 * and where, its headline (the scenario's first step), and links to walk
 * through it in the journeys viewer and to its ArchiMate view (archimate/build.py gives each moment's view the
 * moment's id as its slug).
 *
 * It also writes the home page's hero, the story in one sentence, as the
 * journeys viewer's overview draws it (VaxLink's layout), from the workshop's
 * `presentation` (workshops/pilgrim-policy-questions.workshop.json), with
 * buttons into that overview's walkthrough and journey map.
 *
 * In each language (owner, 2026-11-13: "translate ... the cards"): every
 * string the cards and the hero show is in `translations/<locale>/journey-cards.pot`,
 * and a locale whose `journey-cards.po` translates any of them gets its own
 * `journey-cards-<locale>.html` and `journey-hero-<locale>.html`, which the
 * home page's `{% lang-fragment %}` picks on that locale's page (fhir-harness
 * `resolveLangFragments`). A string with no translation stays English. Those
 * pages sit one level down (`<locale>/index.html`), so their links and images
 * point one level up.
 *
 * Usage:
 *   bun input/scripts/journey-cards.ts           # write the includes (English and each translated locale) and the templates
 *   bun input/scripts/journey-cards.ts --check   # fail when a committed file is stale
 */
import { existsSync, readFileSync, readdirSync, writeFileSync, mkdirSync } from "node:fs";
import { join, resolve } from "node:path";
import { parsePo } from "../../cat-harness-tools/pipeline/po-inject.ts";
import { formatPot, potWithoutTimestamp, type PotEntry } from "../../cat-harness-tools/pipeline/pot-extract.ts";

const ROOT = resolve(import.meta.dir, "..", "..");
const OUT = join(ROOT, "input/includes/journey-cards.html");
const HERO = join(ROOT, "input/includes/journey-hero.html");
const WORKSHOP = "pilgrim-policy-questions";
const VIEWER = "en/smart-ips-pilgrimage/journeys/smart-ips-pilgrimage";
const VERSION = /^version:\s*(\S+)/m.exec(readFileSync(join(ROOT, "sushi-config.yaml"), "utf8"))![1];
const VIEWS = `en/smart-ips-pilgrimage/archimate/${VERSION}/view`;
const LOCALES = ["ar", "es", "fr", "ru", "zh"];

/** The page's language: a string to its translation (English when none), and the path up to the site root. */
interface Lang { t: (s: string) => string; up: string; rtl?: boolean }
const ENGLISH: Lang = { t: (s) => s, up: "" };
/** Languages written right to left: the hero's arrows point the other way, and its small heading is not letter-spaced, which would break the script's joins. */
const RTL = new Set(["ar"]);

/** The words the cards and the hero say themselves, not read from a scenario. */
const UI = {
  walkTitle: "Walk through this moment",
  walk: "Walk through it",
  archimate: "ArchiMate view",
  kicker: "The story in one sentence",
  start: "Start the walkthrough",
  map: "See the whole journey map",
  overview: "Overview, people and policy questions",
} as const;

interface Step { headline?: string; narrative?: string }
interface Scenario { id: string; title: string; when?: string; where?: string; partOf?: string; steps?: Step[] }

const esc = (s: string) => s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");

function moments(): Scenario[] {
  const dir = join(ROOT, "user-scenarios");
  return readdirSync(dir).filter((f) => f.endsWith(".json")).sort()
    .map((f) => JSON.parse(readFileSync(join(dir, f), "utf8")) as Scenario)
    .filter((s) => s.partOf);
}

export function cards(lang: Lang = ENGLISH): string {
  const { t, up } = lang;
  const out = [
    "<!-- Generated by input/scripts/journey-cards.ts from user-scenarios/. Do not edit; edit the scenarios and rerun. -->",
    '<div style="display:grid;grid-template-columns:repeat(auto-fill,minmax(max(200px,calc((100% - 42px) / 4)),1fr));gap:14px;margin:12px 0 24px">',
  ];
  for (const m of moments()) {
    const code = m.id.split("-")[0];
    const walk = `${up}${VIEWER}/${m.id}/`;
    const [label, ...rest] = m.title.split(" · ");
    const name = rest.join(" · ") || m.title;
    const text = m.steps?.[0]?.headline ?? m.steps?.[0]?.narrative ?? "";
    out.push(
      '<div style="border:1px solid #e2e8f0;border-radius:14px;padding:14px;background:#fff;color:#1e293b">',
      `<a href="${walk}" title="${esc(t(UI.walkTitle))}"><img src="${up}pilgrim/${code}.webp" alt="${esc(rest.length ? `${label} · ${t(name)}` : t(m.title))}" style="width:100%;border-radius:10px"/></a>`,
      `<div style="font-weight:700;font-size:1.1em;margin-top:8px">${esc(t(name))}</div>`,
      `<div style="font-size:.8em;color:#64748b">${esc([m.when && t(m.when), m.where && t(m.where), label].filter(Boolean).join(" · "))}</div>`,
      `<p style="font-size:.9em;margin:6px 0">${esc(t(text))}</p>`,
      `<div style="font-size:.85em"><a href="${walk}"><b>${esc(t(UI.walk))}</b></a> · <a href="${up}${VIEWS}/${m.id}/">${esc(t(UI.archimate))}</a></div>`,
      "</div>",
    );
  }
  out.push("</div>", "");
  return out.join("\n");
}

interface Presentation { story?: string; lede?: string }

function workshop(): { title: string; presentation?: Presentation } {
  return JSON.parse(readFileSync(join(ROOT, "workshops", `${WORKSHOP}.workshop.json`), "utf8")) as { title: string; presentation?: Presentation };
}

export function hero(lang: Lang = ENGLISH): string {
  const { t, up, rtl } = lang;
  const w = workshop();
  const p = w.presentation ?? {};
  const base = `${up}${VIEWER}/workshops/${WORKSHOP}`;
  const button = (href: string, text: string, primary: boolean) =>
    `<a href="${href}" style="display:inline-block;padding:9px 16px;border-radius:8px;font-weight:600;text-decoration:none;` +
    (primary ? "background:#0ea5e9;color:#fff" : "background:rgba(255,255,255,.1);color:#fff;border:1px solid rgba(255,255,255,.18)") + `">${text}</a>`;
  return [
    "<!-- Generated by input/scripts/journey-cards.ts from the workshop's presentation. Do not edit; edit the workshop and rerun. -->",
    '<div style="background:linear-gradient(135deg,#0f172a,#0c2a43);color:#fff;border-radius:16px;padding:28px 32px;margin:8px 0 20px">',
    rtl
      ? `<div style="font-size:.85em;color:#7dd3fc">${esc(t(UI.kicker))}</div>`
      : `<div style="font-family:monospace;font-size:.75em;letter-spacing:.12em;color:#7dd3fc;text-transform:uppercase">${esc(t(UI.kicker))}</div>`,
    `<div style="font-size:1.6em;font-weight:700;line-height:1.25;margin:10px 0 12px;max-width:44em">${esc(t(p.story ?? w.title))}</div>`,
    p.lede ? `<p style="color:#cbd5e1;margin:0 0 18px;max-width:52em">${esc(t(p.lede))}</p>` : "",
    `<div style="display:flex;gap:10px;flex-wrap:wrap">${button(`${base}/walkthrough/P0/`, `${rtl ? "&#9665;" : "&#9655;"} ${esc(t(UI.start))}`, true)}${button(`${base}/map/`, `${esc(t(UI.map))} ${rtl ? "&#8592;" : "&#8594;"}`, false)}${button(`${base}/overview/`, esc(t(UI.overview)), false)}</div>`,
    "</div>",
    "",
  ].filter((l) => l !== "").join("\n") + "\n";
}

/** Every string a card or the hero shows, as the template a translator works from. */
export function entries(): PotEntry[] {
  const out: PotEntry[] = [];
  const seen = new Set<string>();
  const add = (source: string, msgid: string | undefined, comment: string) => {
    if (!msgid || seen.has(msgid)) return;
    seen.add(msgid);
    out.push({ source, line: out.length + 1, msgid, kind: "ui-string", comment });
  };
  for (const m of moments()) {
    const src = `user-scenarios/${m.id}.json`;
    const [, ...rest] = m.title.split(" · ");
    add(src, rest.join(" · ") || m.title, `Moment ${m.id.split("-")[0]}: its title on the home page's card.`);
    add(src, m.when, "When the moment happens, on its card.");
    add(src, m.where, "Where the moment happens, on its card.");
    add(src, m.steps?.[0]?.headline ?? m.steps?.[0]?.narrative, `Moment ${m.id.split("-")[0]}: its card's one-line summary.`);
  }
  const w = workshop();
  const src = `workshops/${WORKSHOP}.workshop.json`;
  add(src, w.presentation?.story ?? w.title, "The home page's story in one sentence.");
  add(src, w.presentation?.lede, "The line under the story in one sentence.");
  const ui: Record<keyof typeof UI, string> = {
    walkTitle: "Tooltip on a card's picture.",
    walk: "A card's link into the journeys viewer.",
    archimate: "A card's link to the moment's ArchiMate view.",
    kicker: "Small heading over the story in one sentence.",
    start: "The hero's first button.",
    map: "The hero's second button.",
    overview: "The hero's third button.",
  };
  for (const k of Object.keys(UI) as (keyof typeof UI)[]) add("input/scripts/journey-cards.ts", UI[k], ui[k]);
  return out;
}

/** A locale's translations, or `undefined` when its catalogue translates nothing. */
function langOf(locale: string): Lang | undefined {
  const path = join(ROOT, "translations", locale, "journey-cards.po");
  if (!existsSync(path)) return undefined;
  const po = parsePo(readFileSync(path, "utf8"));
  if (![...po.values()].some((v) => v.trim())) return undefined;
  return { t: (s) => po.get(s)?.trim() || s, up: "../", rtl: RTL.has(locale) };
}

const fragment = (base: string, locale?: string) => join(ROOT, "input/includes", `${base}${locale ? `-${locale}` : ""}.html`);

function emit(path: string, want: string, check: boolean, same: (a: string, b: string) => boolean = (a, b) => a === b): boolean {
  const rel = path.slice(ROOT.length + 1);
  if (check) {
    const have = existsSync(path) ? readFileSync(path, "utf8") : "";
    if (!same(have, want)) {
      console.error(`${rel}: stale; run bun input/scripts/journey-cards.ts`);
      return false;
    }
    console.log(`${rel}: current`);
    return true;
  }
  // A template whose only change would be its timestamp is left as it is.
  if (existsSync(path) && same(readFileSync(path, "utf8"), want)) return true;
  mkdirSync(join(path, ".."), { recursive: true });
  writeFileSync(path, want);
  console.log(`${rel}: written`);
  return true;
}

if (import.meta.main) {
  const check = process.argv.includes("--check");
  const results = [emit(fragment("journey-cards"), cards(), check), emit(fragment("journey-hero"), hero(), check)];
  for (const locale of LOCALES) {
    const pot = formatPot(entries(), { projectName: "smart-ips-pilgrimage", locale });
    results.push(emit(join(ROOT, "translations", locale, "journey-cards.pot"), pot, check, (a, b) => potWithoutTimestamp(a) === potWithoutTimestamp(b)));
    const lang = langOf(locale);
    for (const [base, make] of [["journey-cards", cards], ["journey-hero", hero]] as const) {
      const path = fragment(base, locale);
      if (lang) results.push(emit(path, make(lang), check));
      else if (existsSync(path)) {
        console.error(`${path.slice(ROOT.length + 1)}: ${locale} translates none of the cards; delete it`);
        results.push(false);
      }
    }
  }
  if (!results.every(Boolean)) process.exit(1);
}
